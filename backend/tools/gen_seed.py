OUT_LINES = []


class Raw(str):
    """标记一段原样输出的 SQL（如 NOW()），不做引号包裹和转义"""
    pass


def q(v):
    if isinstance(v, Raw):
        return str(v)
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("\\", "\\\\").replace("'", "''") + "'"


def add(sql):
    OUT_LINES.append(sql)


def rows_to_sql(table, columns, rows):
    """rows: list[tuple]，拼成一条多值 INSERT"""
    body = ",\n".join("(" + ", ".join(q(v) for v in r) + ")" for r in rows)
    add("INSERT INTO `%s` (%s) VALUES\n%s;" % (
        table, ", ".join("`%s`" % c for c in columns), body))


