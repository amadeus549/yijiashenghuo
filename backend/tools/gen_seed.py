# 图片目录：默认取仓库里的 frontend/imgs/notes，本地开发可用 IMG_ROOT 覆盖
IMG_ROOT = os.environ.get("IMG_ROOT") or os.path.normpath(
    os.path.join(ROOT, "..", "frontend", "imgs", "notes"))

# 带水印的 WebP 素材不参与（浏览器能显示，但会露出第三方水印）
SKIP = {"4771fefb", "863cc302", "2f07e3c9", "ac2ce2fb"}


def load_images():
    paths = []
    for dirpath, _, names in os.walk(IMG_ROOT):
        for n in names:
            if not n.lower().endswith(".jpg"):
                continue
            if any(n.startswith(s) for s in SKIP):
                continue
            rel = os.path.join(dirpath, n).replace(IMG_ROOT, "").replace("\\", "/")
            paths.append("/imgs/notes" + rel)
    paths.sort()
    if len(paths) < 10:
        raise SystemExit("本地图片太少，请检查 IMG_ROOT 是否正确")
    return paths


IMAGES = load_images()


def imgs(start, count=3):
    """从图片池里连续取 count 张，循环复用"""
    return ",".join(IMAGES[(start + i) % len(IMAGES)] for i in range(count))


